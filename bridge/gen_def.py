"""Generate sl1_bridge.def from the stock Streamline 1.3.3 interposer export list.

Every SL1 export name is re-exported by the bridge.  The 12 API entry points are
mapped onto the bridge implementations; the SL2-only names are exported as real
passthroughs (so SL2-aware third party components probing this DLL work); every
other historical export is mapped to a harmless stub (nothing in the target game
resolves them, verified via PE import scan of all game modules).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), 'bridge', 'interposer133_exports.txt')

MANGLED = {
    '?init@sl@@YA_NAEBUPreferences@1@H@Z': 'Bridge_Init',
    '?shutdown@sl@@YA_NXZ': 'Bridge_Shutdown',
    '?setTag@sl@@YA_NPEBUResource@1@W4BufferType@1@IPEBUExtent@1@@Z': 'Bridge_SetTag',
    '?setConstants@sl@@YA_NAEBUConstants@1@II@Z': 'Bridge_SetConstants',
    '?setFeatureConstants@sl@@YA_NW4Feature@1@PEBXII@Z': 'Bridge_SetFeatureConstants',
    '?getFeatureSettings@sl@@YA_NW4Feature@1@PEBXPEAX@Z': 'Bridge_GetFeatureSettings',
    '?isFeatureSupported@sl@@YA_NW4Feature@1@PEAI@Z': 'Bridge_IsFeatureSupported',
    '?evaluateFeature@sl@@YA_NPEAXW4Feature@1@II@Z': 'Bridge_EvaluateFeature',
}

CNAMES = {
    'slInit': 'Bridge_Init',
    'slShutdown': 'Bridge_Shutdown',
    'slSetTag': 'Bridge_SetTag',
    'slSetConstants': 'Bridge_SetConstants',
    'slSetFeatureConstants': 'Bridge_SetFeatureConstants',
    'slGetFeatureSettings': 'Bridge_GetFeatureSettings',
    'slIsFeatureSupported': 'Bridge_IsFeatureSupported',
    'slEvaluateFeature': 'Bridge_EvaluateFeature',
    'slIsFeatureEnabled': 'Bridge_IsFeatureEnabled',
    'slSetFeatureEnabled': 'Bridge_SetFeatureEnabled',
    'slAllocateResources': 'Bridge_AllocateResources',
    'slFreeResources': 'Bridge_FreeResources',
}

# SL2-only names exposed for external SL2-aware components
EXTRA = {
    'slSetD3DDevice': 'Bridge_PassSetD3DDevice',
    'slGetFeatureFunction': 'Bridge_PassGetFeatureFunction',
    'slSetFeatureLoaded': 'Bridge_PassSetFeatureLoaded',
    'slIsFeatureLoaded': 'Bridge_PassIsFeatureLoaded',
    'slGetNewFrameToken': 'Bridge_PassGetNewFrameToken',
}

# D3D/DXGI proxies: Returnal-StreamlineD3D12RHIPreInit resolves these from
# sl.interposer.dll and installs them as the engine's custom device/factory
# creation functions.  Forwarded to the genuine SL2 interposer's exports.
PROXY = {
    'CreateDXGIFactory': 'Bridge_CreateDXGIFactory',
    'CreateDXGIFactory1': 'Bridge_CreateDXGIFactory1',
    'CreateDXGIFactory2': 'Bridge_CreateDXGIFactory2',
    'DXGIGetDebugInterface1': 'Bridge_DXGIGetDebugInterface1',
    'D3D11CreateDevice': 'Bridge_D3D11CreateDevice',
    'D3D11CreateDeviceAndSwapChain': 'Bridge_D3D11CreateDeviceAndSwapChain',
    'D3D12CreateDevice': 'Bridge_D3D12CreateDevice',
    'D3D12CreateRootSignatureDeserializer': 'Bridge_D3D12CreateRootSignatureDeserializer',
    'D3D12CreateVersionedRootSignatureDeserializer': 'Bridge_D3D12CreateVersionedRootSignatureDeserializer',
    'D3D12EnableExperimentalFeatures': 'Bridge_D3D12EnableExperimentalFeatures',
    'D3D12GetDebugInterface': 'Bridge_D3D12GetDebugInterface',
    'D3D12GetInterface': 'Bridge_D3D12GetInterface',
    'D3D12SerializeRootSignature': 'Bridge_D3D12SerializeRootSignature',
    'D3D12SerializeVersionedRootSignature': 'Bridge_D3D12SerializeVersionedRootSignature',
}

MAPPING = {}
MAPPING.update(MANGLED)
MAPPING.update(CNAMES)
MAPPING.update(PROXY)

def main():
    names = []
    with open(SRC, 'r', encoding='utf-8-sig') as f:
        for line in f:
            line = line.strip().strip('\ufeff')
            if not line or line.startswith('#') or line.startswith('exports:'):
                continue
            names.append(line)

    out = []
    out.append('; generated by gen_def.py - do not edit')
    out.append('EXPORTS')
    seen = set()
    mapped = 0
    stubbed = 0
    for n in names:
        if n in seen:
            continue
        seen.add(n)
        internal = MAPPING.get(n)
        if internal:
            mapped += 1
        else:
            internal = 'Bridge_Stub'
            stubbed += 1
        out.append('    %s=%s' % (n, internal))

    # extras not present in the 1.3.3 list
    for n, internal in EXTRA.items():
        if n in seen:
            continue
        seen.add(n)
        out.append('    %s=%s' % (n, internal))
        mapped += 1

    dst = os.path.join(HERE, 'sl1_bridge.def')
    with open(dst, 'w', encoding='ascii') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote %s: %d exports (%d mapped, %d stubbed)' % (dst, len(seen), mapped, stubbed))

if __name__ == '__main__':
    main()
